import random
import time

def intro():
    print("\n" + "="*50)
    print(" ВЫПРОГРАММИРОВАЛИСЬ ИЗ РЕАЛЬНОСТИ...")
    print(" Вы очнулись в темной заброшенной лаборатории.")
    print(" Впереди двеле двери: Левая (синяя) и Правая (красная).")
    print("="*50)
  
def play_game():
    intro()
    inventory = []
    
    # Шаг 1: Выбор двери
    choice = input("\nКуда пойдете? (левая / правая): ").strip().lower()
    
    if choice == "левая":
        print("\n Вы зашли в медицинский кабинет. На столе лежит блестящий скальпель.")
        take_item = input("Взять скальпель? (да / нет): ").strip().lower()
        if take_item == "да":
            inventory.append("скальпель")
            print("🎒 Скальпель добавлен в инвентарь.")
        
        print("\nВдруг из шкафа вырывается мутировавший подопытный кролик!")
        action = input("Что делать? (атаковать / бежать): ").strip().lower()
        
        if action == "атаковать":
            if "скальпель" in inventory:
                print("⚔️ Вы отбились скальпелем! Кролик с позором убежал. Вы находите потайной выход.")
                print(" ПОБЕДА! Вы спаслись!")
            else:
                print(" Вы попытались атаковать кролика голыми руками... Но он оказался слишком свирепым.")
                print("☠️ КОНЕЦ ИГРЫ: Кролик защекотал вас до смерти.")
                return
        else:
            print("💨 Вы в панике побежали назад, споткнулись о провод и упали в вентиляционную шахту...")
            time.sleep(1)
            print("🕳️ Шахта привела вас прямиком на улицу! Вы свободны, хоть и в синяках.")
            print(" ПОБЕДА (с приключениями)!")
            
    elif choice == "правая":
        print("\n Вы попали в главный компьютерный зал. На экране мигает надпись: 'Введите пароль'")
        print("Вам нужно угадать число от 1 до 5, у вас есть 3 попытки, иначе включится самоликвидация.")
        
        secret_number = random.randint(1, 5)
        attempts = 3
        
        for i in range(attempts):
            try:
                guess = int(input(f"Попытка {i+1}/3. Ваше число: "))
                if guess == secret_number:
                    print("🔓 Пароль принят! Главные ворота комплекса открылись!")
                    print("🏆 ПОБЕДА! Вы вышли через парадный вход.")
                    return
                elif guess < secret_number:
                    print("❌ Мимо. Загаданное число больше.")
                else:
                    print("❌ Мимо. Загаданное число меньше.")
            except ValueError:
                print(" Вводите только числа!")
        
        print(f"\n☠️ Попытки кончились! Правильный пароль был: {secret_number}")
        print("🚨 Включилась система очистки помещения. Лаборатория заблокирована.")
        print(" КОНЕЦ ИГРЫ.")
        
    else:
        print("\n Вы слишком долго думали, и вас съела нагрянувшая темнота...")
        print("☠️ КОНЕЦ ИГРЫ.")

# Запуск игры
if __name__ == "__main__":
    play_game()
